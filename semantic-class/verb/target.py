# 採る品詞。一段(v1・v1-s)、五段の全種(v5r など v5 で始まるもの)、カ変(vk)、
# ザ変(vz。「命ずる」の類で、名詞の表では判定できない)である。
VERB_POS_EXACT = {"v1", "v1-s", "vk", "vz"}
VERB_POS_PREFIX = "v5"


def is_target_pos(pos):
    """サ変を除く動詞の語義を採る。

    サ変(vs・vs-i・vs-s・vs-c)は「勉強する」の「する」前の形を体の類の表で
    名詞として判定できるため、この表の対象にしない。二段・四段などの古典活用
    (v2*・v4*・vr・vn)は、持ち込みに入らないことで落ちる。
    """
    return any(p in VERB_POS_EXACT or p.startswith(VERB_POS_PREFIX) for p in pos)


