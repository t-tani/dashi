#
# ここに書く当否は自動の判定(LLM)であり、人手の確認を経ていない。
#
# 基準はこれまでと同じである。定着した用法・専門用語への指摘は誤検出とし、
# 読み手が引っかかる不自然な比喩・擬人化・直訳への指摘を妥当とする。
# role-conflict の妥当の型は、人手の確認で価値を認めた「ループが黙って形が変わる」
# に対する「ループは述語 黙る の主語に立てない」である。
#
# 基準を 1 つ明確にした。誤検出とは、直すべきでない文への指摘で
# ある。理由付け(主語の帰属)が不正確でも、直すべき箇所を指した指摘は誤検出と
# 数えない。裁くのは読み手の役に立つかであって、検出の機構が正確かではない。
# 「黙って + 動詞」の型を含む文への指摘は、係り先を取り違えていても妥当である。
#
# 比較は旧表(分類語彙表由来)と Haiku v2 表(訂正後の方針、43 分類)で、
# 設定ファイルは 2 つとも同一である。違うのは意味分類表だけである。

